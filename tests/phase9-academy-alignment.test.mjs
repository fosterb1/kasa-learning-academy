import test from 'node:test'
import assert from 'node:assert/strict'
import {readFile} from 'node:fs/promises'
const read = path => readFile(new URL('../' + path,import.meta.url),'utf8')
test('curriculum accurately distinguishes core Kasa from experimental imports',async()=>{
 const index=await read('src/app/(site)/learn/syntax/page.tsx')
 const lesson=await read('src/app/(site)/learn/modules/page.tsx')
 const glossary=await read('src/app/(site)/glossary/page.tsx')
 assert.match(index,/href="\/learn\/modules"/)
 assert.match(index,/experimental/)
 assert.doesNotMatch(index,/core grammar does not yet include Python or JavaScript features such as classes, imports/)
 assert.match(lesson,/fa math firi stdlib: m/)
 assert.match(lesson,/fa collections firi stdlib: c/)
 assert.match(lesson,/60\\nnokware/)
 assert.match(lesson,/not the editor inside an ordinary lesson/)
 assert.match(glossary,/Experimental module vocabulary/)
 assert.match(glossary,/href="\/language-status"/)
})
test('embedded lesson runner cannot misrepresent pinned module support',async()=>{
 const editor=await read('src/components/Playground.tsx')
 const smallWorker=await read('public/kasa-worker.js')
 const largeWorker=await read('public/kasa-studio/worker.js')
 assert.match(editor,/needsStudioModules/)
 assert.match(editor,/if \(needsStudioModules\)/)
 assert.match(editor,/href="\/playground"/)
 assert.match(smallWorker,/importScripts\('\/kasa-runtime\.js'\)/)
 assert.doesNotMatch(smallWorker,/KASA_HAS_PINNED_MODULES/)
 assert.match(largeWorker,/KASA_HAS_PINNED_MODULES = true/)
})
test('feature status page separates experimental JS from native and bytecode',async()=>{
 const status=await read('src/app/(site)/language-status/page.tsx')
 assert.match(status,/fa \.\.\. firi stdlib imports/)
 assert.match(status,/Not supported/)
 assert.match(status,/KBC1/)
 assert.match(status,/KBC2/)
 assert.match(status,/Embedded lesson editors/)
})
test('installer page distinguishes previews from publicly supported downloads',async()=>{
 const downloads=await read('src/app/(site)/downloads/page.tsx')
 const guides=await read('src/app/(site)/guides/page.tsx')
 assert.match(downloads,/Windows/)
 assert.match(downloads,/Apple Silicon/)
 assert.match(downloads,/Linux/)
 assert.match(downloads,/no Windows, macOS or Linux installer has yet been approved/)
 assert.match(downloads,/SHA-256/)
 assert.doesNotMatch(downloads,/href="[^"]+\.(?:exe|pkg|deb|rpm|zip)"/)
 assert.match(guides,/href="\/downloads"/)
})
test('CMS lesson data is not modified by Phase 9 Academy references',async()=>{
 const seed=await read('scripts/seed.ts')
 assert.match(seed,/if \(await existing\('lessons'/)
 assert.match(seed,/if\s*\(\s*await existing\('challenges'/)
 const packageFile=JSON.parse(await read('package.json'))
 assert.match(packageFile.scripts.build,/phase9-academy-alignment\.test\.mjs/)
})
